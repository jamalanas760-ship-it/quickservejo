-- Repair QuickServe Storage buckets idempotently.
-- PDF uploads use menu-pdfs; restaurant images use restaurant-media.

insert into storage.buckets (id, name, public, file_size_limit)
values ('menu-pdfs', 'menu-pdfs', true, 104857600)
on conflict (id) do update
set public = true,
    file_size_limit = 104857600;

insert into storage.buckets (id, name, public, file_size_limit)
values ('restaurant-media', 'restaurant-media', false, 5242880)
on conflict (id) do nothing;

-- PDF menu policies.
drop policy if exists "menu-pdfs public read" on storage.objects;
drop policy if exists "menu-pdfs authenticated upload" on storage.objects;
drop policy if exists "menu-pdfs authenticated update" on storage.objects;
drop policy if exists "menu-pdfs authenticated delete" on storage.objects;

create policy "menu-pdfs public read"
on storage.objects
for select
to public
using (bucket_id = 'menu-pdfs');

create policy "menu-pdfs authenticated upload"
on storage.objects
for insert
to authenticated
with check (bucket_id = 'menu-pdfs');

create policy "menu-pdfs authenticated update"
on storage.objects
for update
to authenticated
using (bucket_id = 'menu-pdfs')
with check (bucket_id = 'menu-pdfs');

create policy "menu-pdfs authenticated delete"
on storage.objects
for delete
to authenticated
using (bucket_id = 'menu-pdfs');

-- Restaurant media policies. Restrict writes to authenticated users while
-- allowing signed URLs to be generated by authenticated application users.
drop policy if exists "restaurant-media authenticated read" on storage.objects;
drop policy if exists "restaurant-media authenticated upload" on storage.objects;
drop policy if exists "restaurant-media authenticated update" on storage.objects;
drop policy if exists "restaurant-media authenticated delete" on storage.objects;

create policy "restaurant-media authenticated read"
on storage.objects
for select
to authenticated
using (bucket_id = 'restaurant-media');

create policy "restaurant-media authenticated upload"
on storage.objects
for insert
to authenticated
with check (bucket_id = 'restaurant-media');

create policy "restaurant-media authenticated update"
on storage.objects
for update
to authenticated
using (bucket_id = 'restaurant-media')
with check (bucket_id = 'restaurant-media');

create policy "restaurant-media authenticated delete"
on storage.objects
for delete
to authenticated
using (bucket_id = 'restaurant-media');
