create or replace function public.open_cash_session(_opening_float numeric default 0,_staff_id uuid default null)
returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare _restaurant_id uuid; _id uuid;
begin
  select restaurant_id into _restaurant_id
  from public.staff
  where auth_user_id=(select auth.uid()) and is_active
  order by updated_at desc limit 1;
  if _restaurant_id is null or not (
    app.has_capability(_restaurant_id,'manage_payments')
    or app.has_capability(_restaurant_id,'manage_restaurant')
  ) then raise exception 'Cashier access is required'; end if;
  if exists(select 1 from public.cash_sessions where restaurant_id=_restaurant_id and opened_by=(select auth.uid()) and closed_at is null) then
    select id into _id from public.cash_sessions where restaurant_id=_restaurant_id and opened_by=(select auth.uid()) and closed_at is null order by opened_at desc limit 1;
    return _id;
  end if;
  insert into public.cash_sessions(restaurant_id,staff_id,opening_float)
  values(_restaurant_id,_staff_id,greatest(coalesce(_opening_float,0),0))
  returning id into _id;
  return _id;
end;
$$;
revoke all on function public.open_cash_session(numeric,uuid) from public,anon;
grant execute on function public.open_cash_session(numeric,uuid) to authenticated,service_role;

create or replace function public.record_order_payment(
  _order_id uuid,_method text,_amount numeric,_tip numeric default 0,_reference text default '',_cash_session_id uuid default null
) returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare
  _order public.orders%rowtype;
  _id uuid;
  _paid numeric;
begin
  select * into _order from public.orders where id=_order_id for update;
  if _order.id is null then raise exception 'Order not found'; end if;
  if not (
    app.has_capability(_order.restaurant_id,'manage_payments')
    or app.has_capability(_order.restaurant_id,'manage_restaurant')
    or app.is_super_admin()
  ) then raise exception 'Payment access is required'; end if;
  if _method not in ('cash','card','wallet','gift_card','other') then raise exception 'Unsupported payment method'; end if;
  if coalesce(_amount,0)<=0 then raise exception 'Payment amount must be positive'; end if;

  insert into public.payment_transactions(
    restaurant_id,order_id,cash_session_id,transaction_type,method,amount,tip_amount,reference,status
  ) values(
    _order.restaurant_id,_order_id,_cash_session_id,'payment',_method,_amount,greatest(coalesce(_tip,0),0),left(coalesce(_reference,''),200),'completed'
  ) returning id into _id;

  select coalesce(sum(case when transaction_type='payment' and status='completed' then amount else 0 end),0)
       - coalesce(sum(case when transaction_type='refund' and status='completed' then amount else 0 end),0)
  into _paid
  from public.payment_transactions where order_id=_order_id;

  update public.orders
  set tip_amount=tip_amount+greatest(coalesce(_tip,0),0),
      payment_status=case when _paid>=total then 'paid'::public.payment_status else payment_status end,
      status=case when _paid>=total and status='served' then 'paid'::public.order_status else status end,
      updated_at=now()
  where id=_order_id;

  return _id;
end;
$$;
revoke all on function public.record_order_payment(uuid,text,numeric,numeric,text,uuid) from public,anon;
grant execute on function public.record_order_payment(uuid,text,numeric,numeric,text,uuid) to authenticated,service_role;

create or replace function public.refund_order_payment(
  _order_id uuid,_amount numeric,_method text default 'card',_reference text default ''
) returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare _order public.orders%rowtype; _id uuid; _net numeric;
begin
  select * into _order from public.orders where id=_order_id for update;
  if _order.id is null then raise exception 'Order not found'; end if;
  if not (
    app.has_capability(_order.restaurant_id,'manage_payments')
    or app.has_capability(_order.restaurant_id,'manage_restaurant')
    or app.is_super_admin()
  ) then raise exception 'Payment access is required'; end if;
  if coalesce(_amount,0)<=0 then raise exception 'Refund amount must be positive'; end if;
  insert into public.payment_transactions(restaurant_id,order_id,transaction_type,method,amount,reference,status)
  values(_order.restaurant_id,_order_id,'refund',case when _method in ('cash','card','wallet','gift_card','other') then _method else 'other' end,_amount,left(coalesce(_reference,''),200),'completed')
  returning id into _id;
  select coalesce(sum(case when transaction_type='payment' and status='completed' then amount else 0 end),0)
       - coalesce(sum(case when transaction_type='refund' and status='completed' then amount else 0 end),0)
  into _net from public.payment_transactions where order_id=_order_id;
  if _net<=0 then update public.orders set payment_status='refunded',updated_at=now() where id=_order_id; end if;
  return _id;
end;
$$;
revoke all on function public.refund_order_payment(uuid,numeric,text,text) from public,anon;
grant execute on function public.refund_order_payment(uuid,numeric,text,text) to authenticated,service_role;

create or replace function public.close_cash_session(_session_id uuid,_closing_cash numeric,_notes text default '')
returns void
language plpgsql
security definer
set search_path=''
as $$
declare _session public.cash_sessions%rowtype; _expected numeric;
begin
  select * into _session from public.cash_sessions where id=_session_id for update;
  if _session.id is null or _session.closed_at is not null then raise exception 'Open cash session not found'; end if;
  if not (
    app.has_capability(_session.restaurant_id,'manage_payments')
    or app.has_capability(_session.restaurant_id,'manage_restaurant')
    or app.is_super_admin()
  ) then raise exception 'Payment access is required'; end if;
  select _session.opening_float
    + coalesce(sum(case when transaction_type='payment' and method='cash' and status='completed' then amount else 0 end),0)
    - coalesce(sum(case when transaction_type='refund' and method='cash' and status='completed' then amount else 0 end),0)
  into _expected
  from public.payment_transactions where cash_session_id=_session_id;
  update public.cash_sessions
  set closed_at=now(),closed_by=(select auth.uid()),closing_cash=_closing_cash,expected_cash=_expected,
      variance=coalesce(_closing_cash,0)-_expected,notes=left(coalesce(_notes,''),1000)
  where id=_session_id;
end;
$$;
revoke all on function public.close_cash_session(uuid,numeric,text) from public,anon;
grant execute on function public.close_cash_session(uuid,numeric,text) to authenticated,service_role;

