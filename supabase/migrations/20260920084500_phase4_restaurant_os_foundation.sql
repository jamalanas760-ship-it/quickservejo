create or replace function public.toggle_time_clock(_restaurant_id uuid)
returns table(action text,entry_id uuid,at timestamptz)
language plpgsql
security definer
set search_path=''
as $$
declare _staff_id uuid; _entry uuid; _at timestamptz:=now();
begin
  select id into _staff_id from public.staff
  where restaurant_id=_restaurant_id and auth_user_id=(select auth.uid()) and is_active limit 1;
  if _staff_id is null then raise exception 'Active staff profile not found'; end if;
  select id into _entry from public.staff_time_entries where staff_id=_staff_id and clock_out is null order by clock_in desc limit 1 for update;
  if _entry is null then
    insert into public.staff_time_entries(restaurant_id,staff_id,clock_in) values(_restaurant_id,_staff_id,_at) returning id into _entry;
    return query select 'clocked_in'::text,_entry,_at;
  else
    update public.staff_time_entries set clock_out=_at where id=_entry;
    return query select 'clocked_out'::text,_entry,_at;
  end if;
end;
$$;
