create or replace function public.refresh_restaurant_usage(_restaurant_id uuid)
returns void
language plpgsql
security definer
set search_path=''
as $$
begin
  if not (app.is_super_admin() or app.has_capability(_restaurant_id,'manage_restaurant')) then raise exception 'Restaurant management access is required'; end if;
  insert into public.saas_usage_daily(restaurant_id,usage_date,orders_count,active_staff,tables_count,menu_items_count)
  select _restaurant_id,current_date,
    (select count(*) from public.orders where restaurant_id=_restaurant_id and created_at>=date_trunc('month',now())),
    (select count(*) from public.staff where restaurant_id=_restaurant_id and is_active),
    (select count(*) from public.restaurant_tables where restaurant_id=_restaurant_id and is_active),
    (select count(*) from public.menu_items where restaurant_id=_restaurant_id and is_available)
  on conflict(restaurant_id,usage_date) do update set
    orders_count=excluded.orders_count,active_staff=excluded.active_staff,tables_count=excluded.tables_count,menu_items_count=excluded.menu_items_count;
end;
$$;
