create table if not exists public.public_rate_limits (
  rate_key text not null,
  window_started_at timestamptz not null,
  hits integer not null default 0,
  primary key(rate_key,window_started_at)
);

create or replace function app.enforce_public_rate_limit(_key text,_max_hits integer,_window_seconds integer)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  _window timestamptz;
  _hits integer;
begin
  if _max_hits <= 0 or _window_seconds <= 0 then return; end if;
  _window := to_timestamp(floor(extract(epoch from now())/_window_seconds)*_window_seconds);
  insert into public.public_rate_limits(rate_key,window_started_at,hits)
  values(left(_key,240),_window,1)
  on conflict(rate_key,window_started_at)
  do update set hits=public.public_rate_limits.hits+1
  returning hits into _hits;
  if _hits > _max_hits then
    raise exception 'Too many requests. Please try again shortly.' using errcode='P0001';
  end if;
end;
$$;
revoke all on function app.enforce_public_rate_limit(text,integer,integer) from public,anon,authenticated;
grant execute on function app.enforce_public_rate_limit(text,integer,integer) to service_role;

