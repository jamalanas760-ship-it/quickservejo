create or replace function app.consume_order_inventory(_order_id uuid)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  _order public.orders%rowtype;
  _line record;
  _cost numeric;
  _qty numeric;
begin
  select * into _order from public.orders where id=_order_id;
  if _order.id is null then return; end if;
  insert into public.erp_order_consumptions(order_id,restaurant_id)
  values(_order.id,_order.restaurant_id)
  on conflict(order_id) do nothing;
  if not found then return; end if;

  for _line in
    select ri.inventory_item_id,
           sum((oi.quantity::numeric * ri.quantity * (1 + ri.waste_percent/100.0)) / greatest(r.yield_quantity,0.000001)) as qty
    from public.order_items oi
    join public.erp_menu_recipes r on r.menu_item_id=oi.menu_item_id and r.restaurant_id=oi.restaurant_id
    join public.erp_recipe_items ri on ri.recipe_id=r.id and ri.restaurant_id=r.restaurant_id
    where oi.order_id=_order_id
    group by ri.inventory_item_id
  loop
    _qty:=_line.qty;
    select coalesce((
      select m.unit_cost from public.erp_stock_movements m
      where m.restaurant_id=_order.restaurant_id and m.item_id=_line.inventory_item_id and m.unit_cost>0
      order by m.created_at desc limit 1
    ),0) into _cost;
    begin
      insert into public.erp_stock_movements(
        restaurant_id,item_id,quantity,unit_cost,movement_type,reason,created_by
      ) values(
        _order.restaurant_id,_line.inventory_item_id,-_qty,_cost,'issue',
        'Recipe consumption · '||_order.order_number,
        coalesce((select auth.uid()),'00000000-0000-0000-0000-000000000000'::uuid)
      );
    exception when others then
      insert into public.system_events(restaurant_id,severity,source,event_type,message,metadata)
      values(_order.restaurant_id,'warning','inventory','recipe_consumption_failed',sqlerrm,jsonb_build_object('order_id',_order.id,'inventory_item_id',_line.inventory_item_id,'quantity',_qty));
    end;
  end loop;
end;
$$;

create or replace function app.on_order_recipe_consumption()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
begin
  if new.status in ('accepted','preparing') and old.status is distinct from new.status then
    perform app.consume_order_inventory(new.id);
  end if;
  return new;
end;
$$;
drop trigger if exists trg_order_recipe_consumption on public.orders;
create trigger trg_order_recipe_consumption
after update of status on public.orders
for each row execute function app.on_order_recipe_consumption();

