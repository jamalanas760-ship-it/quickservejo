  _severity text,
  _event_type text,
  _message text,
  _route text default null,
  _metadata jsonb default '{}'::jsonb,
  _restaurant_id uuid default null
) returns void
language plpgsql
security definer
set search_path=''
as $$
begin
  if (select auth.uid()) is null then return; end if;
  if _restaurant_id is not null and not app.has_restaurant_access(_restaurant_id) and not app.is_super_admin() then
    _restaurant_id := null;
  end if;
  insert into public.system_events(restaurant_id,severity,source,event_type,message,route,metadata,user_id)
  values(
    _restaurant_id,
