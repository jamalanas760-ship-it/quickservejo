create or replace function app.upsert_order_guest(
  _restaurant_id uuid,_name text,_phone text,_email text
) returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare _id uuid;
begin
  if nullif(btrim(coalesce(_phone,'')),'') is null and nullif(btrim(coalesce(_email,'')),'') is null then return null; end if;
  if nullif(btrim(coalesce(_phone,'')),'') is not null then
    select id into _id from public.crm_guests where restaurant_id=_restaurant_id and phone=btrim(_phone) limit 1;
  end if;
  if _id is null and nullif(btrim(coalesce(_email,'')),'') is not null then
    select id into _id from public.crm_guests where restaurant_id=_restaurant_id and lower(email)=lower(btrim(_email)) limit 1;
  end if;
  if _id is null then
    insert into public.crm_guests(restaurant_id,name,phone,email)
    values(_restaurant_id,nullif(btrim(coalesce(_name,'')),''),nullif(btrim(coalesce(_phone,'')),''),nullif(lower(btrim(coalesce(_email,''))),'')) returning id into _id;
  else
    update public.crm_guests set
      name=coalesce(nullif(btrim(coalesce(_name,'')),''),name),
      phone=coalesce(nullif(btrim(coalesce(_phone,'')),''),phone),
      email=coalesce(nullif(lower(btrim(coalesce(_email,''))),''),email),
      updated_at=now()
    where id=_id;
  end if;
  insert into public.crm_loyalty_accounts(guest_id,restaurant_id) values(_id,_restaurant_id) on conflict(guest_id) do nothing;
  return _id;
end;
$$;

create or replace function public.place_public_order_v2(
  _qr_token text,_items jsonb,_notes text default null,_guest_name text default null,_guest_phone text default null,_guest_email text default null
) returns table(order_id uuid,order_number text,public_token text,total numeric,currency text)
language plpgsql
security definer
set search_path=''
as $$
declare _result record; _restaurant_id uuid; _guest_id uuid;
begin
  perform app.enforce_public_rate_limit('order:'||coalesce(_qr_token,''),8,60);
  select t.restaurant_id into _restaurant_id from public.restaurant_tables t where t.qr_token=btrim(_qr_token) and t.is_active limit 1;
  if _restaurant_id is null then raise exception 'table not found'; end if;
  select * into _result from app.place_public_order(_qr_token,_items,_notes);
  _guest_id:=app.upsert_order_guest(_restaurant_id,_guest_name,_guest_phone,_guest_email);
  update public.orders set
    guest_id=_guest_id,
    guest_name=nullif(btrim(coalesce(_guest_name,'')),''),
    guest_phone=nullif(btrim(coalesce(_guest_phone,'')),''),
    guest_email=nullif(lower(btrim(coalesce(_guest_email,''))),'')
  where id=_result.order_id;
  return query select _result.order_id,_result.order_number,_result.public_token,_result.total,_result.currency;
end;
$$;
revoke all on function public.place_public_order_v2(text,jsonb,text,text,text,text) from public;
grant execute on function public.place_public_order_v2(text,jsonb,text,text,text,text) to anon,authenticated;

create or replace function app.on_paid_order_guest()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare _enabled boolean; _points integer; _rate numeric;
begin
  if new.payment_status='paid' and old.payment_status is distinct from new.payment_status and new.guest_id is not null then
    update public.crm_guests set visits=visits+1,lifetime_spend=lifetime_spend+new.total,last_visit_at=now(),updated_at=now() where id=new.guest_id;
    select enable_loyalty,loyalty_points_per_currency into _enabled,_rate from public.restaurant_settings where restaurant_id=new.restaurant_id;
    if coalesce(_enabled,false) then
      _points:=floor(new.total*coalesce(_rate,10))::integer;
      if _points>0 then
        insert into public.crm_loyalty_ledger(restaurant_id,guest_id,points,reason,source_order_id)
        values(new.restaurant_id,new.guest_id,_points,'Order reward',new.id)
        on conflict do nothing;
        if found then
          update public.crm_loyalty_accounts set points=points+_points,updated_at=now() where guest_id=new.guest_id;
        end if;
      end if;
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_paid_order_guest on public.orders;
create trigger trg_paid_order_guest after update of payment_status on public.orders
for each row execute function app.on_paid_order_guest();

