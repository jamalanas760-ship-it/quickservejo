  add column if not exists max_active_orders integer not null default 100;
create table if not exists public.staff_time_entries (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  staff_id uuid not null references public.staff(id) on delete cascade,
  clock_in timestamptz not null default now(),
  clock_out timestamptz,
  break_minutes integer not null default 0 check(break_minutes>=0),
  notes text not null default '',
  approved_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.staff_leave_requests (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  staff_id uuid not null references public.staff(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  reason text not null default '',
  status text not null default 'pending' check(status in ('pending','approved','rejected','cancelled')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check(end_date>=start_date)
);
create table if not exists public.erp_supplier_invoices (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  supplier_id uuid references public.erp_suppliers(id) on delete set null,
  procurement_request_id uuid references public.erp_procurement_requests(id) on delete set null,
  invoice_number text not null,
  invoice_date date not null default current_date,
  amount numeric not null check(amount>=0),
  tax_amount numeric not null default 0 check(tax_amount>=0),
  status text not null default 'draft' check(status in ('draft','matched','approved','paid','void')),
  file_url text,
  expense_id uuid references public.erp_expenses(id) on delete set null,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(restaurant_id,invoice_number)
);
create table if not exists public.restaurant_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.restaurant_group_members (
  group_id uuid not null references public.restaurant_groups(id) on delete cascade,
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(group_id,restaurant_id)
);
create table if not exists public.saas_usage_daily (
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  usage_date date not null default current_date,
  orders_count integer not null default 0,
  active_staff integer not null default 0,
  tables_count integer not null default 0,
  menu_items_count integer not null default 0,
  storage_bytes bigint not null default 0,
  primary key(restaurant_id,usage_date)
);

