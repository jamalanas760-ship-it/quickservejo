    'web',
    left(coalesce(_event_type,'client_error'),120),
    left(coalesce(_message,'Unknown client error'),2000),
    left(_route,500),
    coalesce(_metadata,'{}'::jsonb),
    (select auth.uid())
  );
end;
$$;
